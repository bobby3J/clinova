import { useEffect, useState } from "react";
import { Link } from "react-router";
import AppShell from "../../components/AppShell";
import BottomNav from "../../components/BottomNav";
import MobileTopBar from "../../components/MobileTopBar";
import { CheckIcon, ChevronLeftIcon, FolderIcon, SparkleIcon } from "../../components/icons";
import { getSubjects, getTopics } from "../../lib/studyLibrary";
import { answerPracticeQuestion, generatePracticeSet } from "../../lib/aiPractice";
import { useAuth } from "../../context/AuthContext";
import { ApiError } from "../../types/common";
import type { Subject, Topic } from "../../types/studyLibrary";
import type { PracticeAnswer, PracticeSet } from "../../types/aiPractice";

type Step = "topics" | "reviewing" | "summary";

export default function AiPractice() {
  const { user } = useAuth();
  const [step, setStep] = useState<Step>("topics");

  const [subjects, setSubjects] = useState<Subject[]>([]);
  const [selectedSubject, setSelectedSubject] = useState<Subject | null>(null);
  const [topics, setTopics] = useState<Topic[]>([]);
  const [loadingTopics, setLoadingTopics] = useState(true);

  const [generating, setGenerating] = useState(false);
  const [generateError, setGenerateError] = useState<string | null>(null);
  const [practiceSet, setPracticeSet] = useState<PracticeSet | null>(null);

  const [currentIndex, setCurrentIndex] = useState(0);
  const [answers, setAnswers] = useState<Record<number, PracticeAnswer>>({});
  const [answering, setAnswering] = useState(false);

  useEffect(() => {
    getSubjects(user?.track ?? undefined)
      .then((res) => setSubjects(res.data))
      .catch(() => {
        // The subject list just stays empty — the topic picker shows an
        // empty state rather than a hard error for this.
      })
      .finally(() => setLoadingTopics(false));
  }, [user?.track]);

  function openSubject(subject: Subject) {
    setSelectedSubject(subject);
    setLoadingTopics(true);
    getTopics(subject.id)
      .then((res) => setTopics(res.data))
      .catch(() => {
        // Topics list stays empty.
      })
      .finally(() => setLoadingTopics(false));
  }

  async function startPractice(topic: Topic) {
    setGenerateError(null);
    setGenerating(true);
    try {
      const res = await generatePracticeSet(topic.id);
      setPracticeSet(res.data);
      setCurrentIndex(0);
      setAnswers({});
      setStep("reviewing");
    } catch (err) {
      setGenerateError(
        err instanceof ApiError
          ? (err.errors?.topic_id?.[0] ?? err.message)
          : "Couldn't generate practice questions.",
      );
    } finally {
      setGenerating(false);
    }
  }

  const currentQuestion = practiceSet?.questions[currentIndex] ?? null;
  const currentAnswer = currentQuestion ? answers[currentQuestion.id] : undefined;

  async function handleAnswer(optionIndex: number) {
    if (!currentQuestion || answering || currentAnswer) return;
    setAnswering(true);
    try {
      const res = await answerPracticeQuestion(currentQuestion.id, optionIndex);
      setAnswers((prev) => ({ ...prev, [currentQuestion.id]: res.data }));
    } catch {
      // The student can just tap again — nothing was recorded locally yet.
    } finally {
      setAnswering(false);
    }
  }

  function handleNext() {
    if (!practiceSet) return;
    if (currentIndex + 1 < practiceSet.questions.length) {
      setCurrentIndex((i) => i + 1);
    } else {
      setStep("summary");
    }
  }

  const correctCount = Object.values(answers).filter((a) => a.is_correct).length;

  return (
    <AppShell background="bg-gray-50">
      <MobileTopBar />
      <div className="px-5 pt-6 pb-28 lg:mx-auto lg:max-w-xl lg:px-0 lg:pt-0 lg:pb-0">
        <div className="mb-6 flex items-center gap-3">
          {step === "topics" && selectedSubject ? (
            <button
              type="button"
              onClick={() => setSelectedSubject(null)}
              className="text-gray-500"
            >
              <ChevronLeftIcon className="h-5 w-5" />
            </button>
          ) : (
            <Link to="/" className="text-gray-500">
              <ChevronLeftIcon className="h-5 w-5" />
            </Link>
          )}
          <h1 className="text-lg font-semibold text-gray-800 lg:text-2xl">AI Practice</h1>
        </div>

        {step === "topics" && (
          <>
            <p className="mb-4 text-xs text-gray-400">
              Questions are generated by AI from your study materials.
            </p>

            {!selectedSubject ? (
              <TopicPickerList
                loading={loadingTopics}
                items={subjects}
                onSelect={openSubject}
                emptyText="No subjects available yet."
              />
            ) : (
              <>
                {generateError && (
                  <div className="mb-4 rounded-xl bg-error-50 px-4 py-3 text-sm text-error-600">
                    {generateError}
                  </div>
                )}
                <TopicPickerList
                  loading={loadingTopics}
                  items={topics}
                  onSelect={startPractice}
                  disabled={generating}
                  emptyText="No topics in this subject yet."
                />
              </>
            )}
          </>
        )}

        {step === "reviewing" && currentQuestion && practiceSet && (
          <>
            <p className="mb-3 text-xs font-medium text-gray-400">
              Question {currentIndex + 1} of {practiceSet.questions.length}
            </p>

            <div className="rounded-2xl border border-gray-100 bg-white p-5 shadow-theme-sm">
              <p className="text-sm font-semibold text-gray-800">{currentQuestion.question}</p>

              <div className="mt-4 flex flex-col gap-2">
                {currentQuestion.options.map((option, i) => {
                  const isSelected = currentAnswer?.selected_option === i;
                  const isCorrectOption = currentAnswer && currentAnswer.correct_option === i;
                  const showResult = Boolean(currentAnswer);

                  let classes = "border-gray-200 bg-white text-gray-700";
                  if (showResult && isCorrectOption) {
                    classes = "border-success-300 bg-success-50 text-success-700";
                  } else if (showResult && isSelected && !isCorrectOption) {
                    classes = "border-error-300 bg-error-50 text-error-700";
                  } else if (isSelected) {
                    classes = "border-brand-300 bg-brand-50 text-brand-700";
                  }

                  return (
                    <button
                      key={i}
                      type="button"
                      disabled={answering || Boolean(currentAnswer)}
                      onClick={() => handleAnswer(i)}
                      className={`rounded-xl border p-3 text-left text-sm font-medium transition-colors disabled:cursor-not-allowed ${classes}`}
                    >
                      {option}
                    </button>
                  );
                })}
              </div>

              {currentAnswer && (
                <div className="mt-4 rounded-xl bg-gray-50 p-3 text-xs text-gray-500">
                  {currentAnswer.explanation}
                </div>
              )}
            </div>

            {currentAnswer && (
              <button
                type="button"
                onClick={handleNext}
                className="mt-5 h-12 w-full rounded-xl bg-brand-500 text-sm font-semibold text-white transition-colors hover:bg-brand-600"
              >
                {currentIndex + 1 < practiceSet.questions.length ? "Next question" : "See results"}
              </button>
            )}
          </>
        )}

        {step === "summary" && practiceSet && (
          <div className="flex flex-col items-center justify-center gap-3 rounded-2xl border border-gray-100 bg-white py-16 text-center shadow-theme-sm">
            <CheckIcon className="h-8 w-8 text-success-500" />
            <p className="text-lg font-bold text-gray-800">
              {correctCount}/{practiceSet.questions.length}
            </p>
            <p className="text-sm text-gray-500">correct on "{practiceSet.topic_name}"</p>
            <div className="mt-2 flex gap-3">
              <button
                type="button"
                onClick={() => {
                  setStep("topics");
                  setSelectedSubject(null);
                  setPracticeSet(null);
                }}
                className="rounded-xl border border-gray-200 px-4 py-2 text-sm font-medium text-gray-600"
              >
                Practice another topic
              </button>
              <Link
                to="/"
                className="rounded-xl bg-brand-500 px-4 py-2 text-sm font-medium text-white"
              >
                Back to Home
              </Link>
            </div>
          </div>
        )}
      </div>

      <BottomNav />
    </AppShell>
  );
}

function TopicPickerList<T extends { id: number; name: string }>({
  loading,
  items,
  onSelect,
  disabled,
  emptyText,
}: {
  loading: boolean;
  items: T[];
  onSelect: (item: T) => void;
  disabled?: boolean;
  emptyText: string;
}) {
  if (loading) {
    return (
      <div className="flex flex-col gap-2">
        {[1, 2, 3].map((i) => (
          <div key={i} className="h-14 animate-pulse rounded-2xl bg-gray-100" />
        ))}
      </div>
    );
  }

  if (items.length === 0) {
    return (
      <div className="flex flex-col items-center justify-center gap-2 rounded-2xl border border-dashed border-gray-200 py-16 text-center">
        <FolderIcon className="h-6 w-6 text-gray-300" />
        <p className="text-xs text-gray-400">{emptyText}</p>
      </div>
    );
  }

  return (
    <ul className="flex flex-col gap-3">
      {items.map((item) => (
        <li key={item.id}>
          <button
            type="button"
            disabled={disabled}
            onClick={() => onSelect(item)}
            className="flex w-full items-center gap-3 rounded-2xl border border-gray-100 bg-white p-4 text-left shadow-theme-sm disabled:cursor-not-allowed disabled:opacity-60"
          >
            <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-brand-50 text-brand-500">
              <SparkleIcon className="h-4 w-4" />
            </span>
            <span className="text-sm font-semibold text-gray-800">{item.name}</span>
          </button>
        </li>
      ))}
    </ul>
  );
}
